// +,-,*,/
// Assignment operator
let a = 22;
let b = 5;
// Arithmetic operator
let sum = a + b;
let sub = a - b;
let mul = a * b;
let div = a / b;
console.log(" SUM Addition:", sum);
console.log(" SUBSTRACTION:", sub);
console.log(" MULTIPLICATION:", mul);
console.log(" DIVIDE:", div);
// Modulus -> % -> It will give you remainder
console.log(a % b);
console.log(13 % 7);
console.log(101 % 2);
console.log(100 % 2);
//  n%2 == 1 - odd number, [ n%2 == 0 , even]
// Exponential **, power 2^3->8
console.log(2 ** 3);
console.log(a ** b); // 22^5->51,53,632
