// 5. SPECIAL NUMERIC VALUES
// ============================================

// Infinity
console.log("Infinity:", Infinity);
console.log("1/0:", 1 / 0);
console.log("-1/0:", -1 / 0);
console.log("typeof Infinity:", typeof Infinity);
/* output:
Infinity: Infinity
1/0: Infinity
-1/0: -Infinity
typeof Infinity: number 
*/
// -Infinity
console.log(" -Infinity:", -Infinity);
// NaN (Not a Number) - result of invalid math
console.log("NaN:", NaN);
console.log("0/0:", 0 / 0);
console.log("'hello'*2:", "hello" * 2);
console.log("typeof NaN:", typeof NaN);
/* output:
NaN: NaN
0/0: NaN
'hello'*2: NaN
typeof NaN: number */
